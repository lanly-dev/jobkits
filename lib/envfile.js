'use strict';
/* Per-kit .env generation + persistent app state.
 *
 * State lives in <userData>/jobkits-state.json:
 *   { settings: { LLM_BASE_URL, LLM_API_KEY, LLM_MODEL },
 *     kits: { <id>: { secrets: {NAME: value}, ports: {ENV: port} } } }
 *
 * Secrets are generated ONCE (crypto random, >=48 chars for token-style
 * secrets) and never regenerated. Ports are probed once: if a default port
 * is taken, the next free port is chosen and persisted. The .env file in the
 * kit source dir is rewritten from state on every start, so settings edits
 * (LLM_*) take effect while secrets/ports stay stable.
 */
const crypto = require('node:crypto');
const fs = require('node:fs');
const net = require('node:net');
const path = require('node:path');

function loadState(statePath) {
  try {
    const s = JSON.parse(fs.readFileSync(statePath, 'utf8'));
    if (s && typeof s === 'object') { s.settings = s.settings || {}; s.kits = s.kits || {}; return s; }
  } catch { /* missing or corrupt -> fresh state */ }
  return { settings: {}, kits: {} };
}

function saveState(statePath, state) {
  fs.mkdirSync(path.dirname(statePath), { recursive: true });
  const tmp = statePath + '.tmp';
  fs.writeFileSync(tmp, JSON.stringify(state, null, 2) + '\n');
  fs.renameSync(tmp, statePath);
}

function genSecret(chars = 48) {
  // base64url alphabet: safe in .env, URLs and connection strings.
  return crypto.randomBytes(Math.ceil(chars * 3 / 4)).toString('base64url').slice(0, chars);
}

function isPortFree(port) {
  return new Promise((resolve) => {
    const srv = net.createServer();
    srv.once('error', () => resolve(false));
    srv.once('listening', () => srv.close(() => resolve(true)));
    srv.listen(port, '127.0.0.1');
  });
}

async function findFreePort(start, maxTries = 200) {
  for (let p = start; p < start + maxTries && p < 65536; p++) {
    if (await isPortFree(p)) return p;
  }
  throw new Error('no free port found near ' + start);
}

// Resolve the port map for a kit: persisted choices win; otherwise probe
// defaults (skipping ports already claimed by this kit's other services).
async function resolvePorts(kit, persisted) {
  const ports = { ...(persisted || {}) };
  const claimed = new Set(Object.values(ports));
  for (const [envName, def] of Object.entries(kit.defaultPorts)) {
    if (Number.isInteger(ports[envName])) continue;
    let p = def;
    if (claimed.has(p) || !(await isPortFree(p))) p = await findFreePort(def);
    while (claimed.has(p)) p = await findFreePort(p + 1);
    ports[envName] = p;
    claimed.add(p);
  }
  return ports;
}

function buildEnvValues(kit, kitState, settings) {
  const values = {};
  for (const name of kit.requiredSecrets) values[name] = kitState.secrets[name];
  for (const [envName, port] of Object.entries(kitState.ports)) values[envName] = String(port);
  for (const name of kit.optionalEnv || []) values[name] = (settings && settings[name]) || '';
  // Freehire-specific conveniences: the browser-facing origins must match the
  // chosen web port or OAuth callbacks / canonical URLs point at dead ports.
  if (kit.id === 'freehire') {
    const webPort = kitState.ports[kit.webPortEnv];
    if (webPort) {
      values.WEB_ORIGIN = `http://localhost:${webPort}`;
      values.FRONTEND_ORIGIN = `http://localhost:${webPort}`;
    }
    // NOTE: upstream freehire's compose pins POSTGRES_USER/PASSWORD/DB and
    // DATABASE_URL to hire/hire internally, so the generated POSTGRES_PASSWORD
    // persisted in state is not consumed by this pinned compose; it is kept
    // (and written to .env) so a future compose that templates it just works.
  }
  return values;
}

function renderEnvFile(kit, values) {
  const lines = [
    `# Generated by jobkits for kit "${kit.id}" — do not edit by hand.`,
    '# Secrets and ports are persisted in jobkits-state.json and stay stable',
    '# across runs; edit LLM settings in the jobkits app instead.',
    '',
  ];
  for (const [k, v] of Object.entries(values)) lines.push(`${k}=${v}`);
  return lines.join('\n') + '\n';
}

/* Ensure srcDir/.env exists and reflects state. Async due to port probing. */
async function ensureKitEnv({ kit, srcDir, statePath, settings }) {
  const state = loadState(statePath);
  const kitState = state.kits[kit.id] || (state.kits[kit.id] = { secrets: {}, ports: {} });
  kitState.secrets = kitState.secrets || {};
  let created = false;
  for (const name of kit.requiredSecrets) {
    if (!kitState.secrets[name]) { kitState.secrets[name] = genSecret(48); created = true; }
  }
  const before = JSON.stringify(kitState.ports || {});
  kitState.ports = await resolvePorts(kit, kitState.ports);
  if (JSON.stringify(kitState.ports) !== before) created = true;
  const effectiveSettings = { ...state.settings, ...(settings || {}) };
  const values = buildEnvValues(kit, kitState, effectiveSettings);
  fs.mkdirSync(srcDir, { recursive: true });
  const envPath = path.join(srcDir, '.env');
  fs.writeFileSync(envPath, renderEnvFile(kit, values));
  saveState(statePath, state);
  return { envPath, values, created, state };
}

module.exports = { loadState, saveState, genSecret, isPortFree, findFreePort, resolvePorts, buildEnvValues, renderEnvFile, ensureKitEnv };
